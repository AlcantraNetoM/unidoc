<script>
document.addEventListener('DOMContentLoaded', function() {
    const roleSelect = document.getElementById('role');
    const categoryField = document.getElementById('categoryField');
    const empresaSelect = document.getElementById('empresa_id');
    const categoriaSelect = document.getElementById('categoria_id');

    // Show/hide category field based on role
    function toggleCategoryField() {
        if (roleSelect.value === 'normal_technician') {
            categoryField.classList.remove('hidden');
        } else {
            categoryField.classList.add('hidden');
            categoriaSelect.value = '';
        }
    }

    // Filter categories based on selected company
    function filterCategories() {
        const selectedEmpresa = empresaSelect.value;
        const categoryOptions = categoriaSelect.querySelectorAll('option');
        
        categoryOptions.forEach(option => {
            if (option.value === '') {
                option.style.display = 'block';
                return;
            }
            
            const empresaId = option.getAttribute('data-empresa');
            if (selectedEmpresa === '' || empresaId === selectedEmpresa) {
                option.style.display = 'block';
            } else {
                option.style.display = 'none';
                if (option.selected) {
                    option.selected = false;
                    categoriaSelect.value = '';
                }
            }
        });
    }

    // Event listeners
    roleSelect.addEventListener('change', toggleCategoryField);
    empresaSelect.addEventListener('change', filterCategories);

    // Initial setup
    toggleCategoryField();
    filterCategories();

    // Form validation
    document.getElementById('editUserForm').addEventListener('submit', function(e) {
        const password = document.getElementById('password').value;
        const passwordConfirmation = document.getElementById('password_confirmation').value;
        
        if (password !== '' && password !== passwordConfirmation) {
            e.preventDefault();
            alert('Password confirmation does not match the new password.');
            return false;
        }
    });
});
</script>
